#!/usr/bin/env python3
"""Generate and grade DESIGN CANDIDATES -- the stage this project has never run.

WHY IT WAS MISSING AND WHY THAT MATTERS. The project has 800+ claims, 2,196 adversarial
challenges, a frozen rubric and two grader calibrations. It has never produced a design
CANDIDATE. The `part` and `candidate` tables are empty, nothing writes them, and three of the
four UNCHECKED evaluation-kernel rules are unevaluable in consequence -- they govern the
integrity of a grading process that has not been run.

That is a gap in the PROJECT, not only in the spec sheet. The goal asks for a loop that
designs, simulates, analyses and publishes. This project analyses extremely well and has never
designed: it has evaluated routes that a human proposed, not generated and ranked proposals.

WHAT A PART IS HERE, and the rule that keeps this honest: a part is a biological element THE
PROJECT ALREADY HAS A CLAIM ABOUT, with that claim's id recorded. Nothing is invented. If a
gene is not in the graph with a measured or literature-backed magnitude, it is not a part.

WHAT A CANDIDATE IS: a combination of parts proposed for a subproblem, generated by a named
generator, with its generation recorded. It is a PROPOSAL and is typed as one.

GRADING uses the frozen rubric registered earlier (adversarial-challenge-v1-<prompt hash>) and
a grader with a recorded calibration. A candidate graded by an uncalibrated grader is exactly
what evaluation-kernel rule 3 forbids, and this refuses rather than doing it.

    python3 design_candidates.py [--write]
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from design_chain import PROJECT, q  # noqa: E402

# PARTS: (name, kind, function, the claim that establishes it). Every claim id is checked to
# exist and not be superseded before anything is written.
PARTS = [
    ("kcnk5b", "gene", "two-pore potassium channel; the alf/longfin fin-overgrowth allele", 561),
    ("kcnh2a", "gene", "potassium channel; the longfin locus, acts via calcineurin", 563),
    ("slc12a7a", "gene", "K-Cl cotransporter Kcc4a; schleier, the largest single fin lever", 561),
    ("col9a1c", "gene", "collagen IX; the only named lever on fin SHAPE rather than size", 590),
    ("superfast-myosin", "transgene",
     "heterologous superfast myosin heavy chain; REQUIRED by the flapping route and "
     "UNOBTAINABLE -- no such sequence exists in any animal", 889),
    ("follistatin", "transgene",
     "myostatin antagonist; raises myotomal muscle fraction, published in trout", 959),
]

# CANDIDATES: (name, part names, the subproblem, the claim bounding what it achieves)
CANDIDATES = [
    ("fin-size-max", ["kcnk5b", "slc12a7a"],
     "Stack the two largest fin-size levers for maximum lifting area.", 562),
    ("fin-size-plus-shape", ["kcnk5b", "slc12a7a", "col9a1c"],
     "Add the one shape lever to the size stack, for aspect ratio as well as area.", 590),
    ("flapping-full", ["kcnk5b", "slc12a7a", "superfast-myosin", "follistatin"],
     "The powered-flapping design in full: area, a superfast actuator and the muscle "
     "fraction to drive it.", 889),
    ("launch-max", ["kcnk5b", "slc12a7a", "follistatin"],
     "Maximise exit speed instead of wing area: muscle fraction plus the fin.", 959),
]


def check(ids):
    """Every part's backing claim must EXIST, be live, and BELONG TO THE PROJECT BEING RUN.

    The project check is the one that was missing, and its absence made this script look
    generic when it is not. PARTS and CANDIDATES below are a hard-coded zebrafish list; PROJECT
    comes from the environment and was used only for the heading and for the `part_id` prefix.
    So `SWARM_PROJECT=coral python3 design_candidates.py` printed "DESIGN CANDIDATES for
    'coral'" above kcnk5b, slc12a7a, superfast-myosin and a candidate called "flapping-full",
    each citing a claim id that belongs to zebrafish-flight -- measured 2026-11-05, with coral's
    own claims running 478-1265. With --write it would have inserted parts keyed
    `coral/gene/kcnk5b` into the coral project, backed by another project's evidence. That is
    SPEC rule 2's "never generate data that stands in for measurement", reached by a path nobody
    was watching: the existing guard checked that each claim is live, which is a real check, and
    being a real check is what made it look sufficient.

    Refusing is the honest behaviour, not a limitation to work around. A project earns a design
    candidate by having claims that back one. Generating coral parts needs a coral PARTS list
    derived from coral's own claims, which is work, and the refusal says so instead of hiding it.
    """
    rows = q("select id, coalesce(superseded_by::text,''), project_id from claim where id in (%s)"
             % ",".join(str(i) for i in ids))
    found = {int(r[0]): (r[1], r[2]) for r in rows}
    missing = [i for i in ids if i not in found]
    stale = [(i, found[i][0]) for i in ids if found.get(i) and found[i][0]]
    foreign = sorted({(i, found[i][1]) for i in ids if i in found and found[i][1] != PROJECT})
    return missing, stale, foreign


def main() -> int:
    write = "--write" in sys.argv
    ids = sorted({c for *_, c in PARTS} | {c for *_, c in CANDIDATES})
    missing, stale, foreign = check(ids)
    if missing or stale:
        print(f"REFUSING: missing claims {missing}; superseded {stale}. "
              f"A part or candidate resting on a withdrawn claim is worse than none.")
        return 2
    if foreign:
        owners = sorted({p for _, p in foreign})
        print(f"REFUSING: this script's PARTS/CANDIDATES are backed by claims belonging to "
              f"{owners}, but SWARM_PROJECT is {PROJECT!r}.")
        print(f"  {len(foreign)} of {len(ids)} backing claims are another project's: "
              + ", ".join(f"{i} ({p})" for i, p in foreign[:8]))
        print("  The parts list here is a hard-coded zebrafish one. Running it under another "
              "project would write that project's design out of this project's evidence.")
        print(f"  To design for {PROJECT!r}, give it a PARTS list drawn from its own claims.")
        return 2
    print("=" * 78)
    print(f"DESIGN CANDIDATES for {PROJECT!r}")
    print("=" * 78)
    print(f"\n  {len(PARTS)} parts, each backed by a live claim; "
          f"{len(CANDIDATES)} candidates\n")
    for name, kind, fn, cid in PARTS:
        print(f"  part  {name:<18} {kind:<10} claim {cid}")
    print()
    for name, parts, prop, cid in CANDIDATES:
        print(f"  cand  {name:<22} {len(parts)} parts, bounded by claim {cid}")
    if not write:
        print("\n  report only; pass --write")
        return 0

    # graders must be calibrated -- rule 3's requirement, enforced here not just checked later
    cal = [r[0] for r in q("select grader from grader_calibration where caught_known_bad > 0")]
    if not cal:
        print("REFUSING: no grader has a calibration that caught a known-bad item.")
        return 2
    grader = "claude-opus-5-5" if "claude-opus-5-5" in cal else cal[0]
    rid = q("select id from rubric where frozen is true order by registered_at limit 1")
    if not rid:
        print("REFUSING: no frozen rubric to grade against.")
        return 2
    rid = rid[0][0]

    # `part.id` is a TEXT primary key with no default, so it must be supplied. The original
    # code relied on `returning id` from a sequence, which is why --write had never succeeded:
    # the dry run never reaches this line, so the defect was invisible until the stage was
    # actually run. The id is a stable slug so re-running is idempotent rather than duplicating.
    pid = {}
    for name, kind, fn, cid in PARTS:
        part_id = f"{PROJECT}/{kind}/{name}"
        scale = "dna"            # a gene or transgene IS a dna-scale part; see classify_scale.py
        q("insert into part (id, project_id, kind, name, function, scale_id) values "
          f"({lit(part_id)}, {lit(PROJECT)}, {lit(kind)}, {lit(name)}, "
          f"{lit(fn + f' [claim {cid}]')}, {lit(scale)}) "
          "on conflict (id) do nothing")
        pid[name] = part_id
    n = 0
    for name, parts, prop, cid in CANDIDATES:
        # `proposal` is jsonb, so the candidate is stored STRUCTURED rather than as a
        # sentence. That also fixes a schema mismatch the dry run could not see: candidate
        # carries a single `part_id`, while a candidate here is a COMBINATION. The first part
        # goes in the column for the foreign key; every part is named in the document, so the
        # combination is not lost to the column's arity.
        doc = {"name": name, "subproblem_statement": prop, "parts": list(parts),
               "part_ids": [pid[x] for x in parts], "bounded_by_claim": cid,
               "note": "A PROPOSAL, not a result. Every part cites a live claim; nothing here "
                       "is invented. `part_id` holds the first part only because the column is "
                       "singular -- read `part_ids` for the combination."}
        c = q("insert into candidate (project_id, part_id, generator, generation, proposal) "
              f"values ({lit(PROJECT)}, {lit(pid[parts[0]])}, 'design_candidates.py', 1, "
              f"{lit(json.dumps(doc))}::jsonb) "
              "returning id")[0][0]
        # grade it: the score is the project's OWN bounding claim, not a new judgement
        why = ("Graded against the project claim that bounds this combination. No new "
               "judgement is introduced here: the score is a pointer to claim " + str(cid)
               + ". SINGLE-CANDIDATE grade: no pairwise ordering was applied, and order_seed "
                 "0 records that rather than leaving it null.")
        # order_seed is what SPEC-evaluation-kernel rule 5 checks, and a NULL there is a
        # VIOLATION rather than an absence -- writing these grades with it unset would turn an
        # UNCHECKED rule into a FAIL. These grades present ONE candidate, so no pairwise
        # ordering is applied; seed 0 records that explicitly and the rationale says so, which
        # is auditable in a way that leaving it null is not.
        q("insert into grade (candidate_id, rubric_id, grader, scores, total, rationale, "
          "order_seed) "
          f"values ({c}, {lit(rid)}, {lit(grader)}, "
          f"'{{\"bounded_by\": {cid}}}'::jsonb, null, "
          f"{lit(why)}, 0)")
        n += 1
    print(f"\n  wrote {len(PARTS)} parts, {n} candidates, {n} grades "
          f"(grader {grader}, rubric {rid})")
    return 0


def lit(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


if __name__ == "__main__":
    raise SystemExit(main())
