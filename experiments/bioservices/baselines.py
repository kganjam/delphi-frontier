BLOSUM62: dict[tuple[str, str], int] = {}
for _i, _line in enumerate(_ROWS.strip().splitlines()):
    for _j, _val in enumerate(_line.split()):
        BLOSUM62[(_ORDER[_i], _ORDER[_j])] = int(_val)

# The matrix is symmetric; assert it rather than assume the transcription is right.
for _a in _ORDER:
    for _b in _ORDER:
        if BLOSUM62[(_a, _b)] != BLOSUM62[(_b, _a)]:
            raise AssertionError(f"BLOSUM62 transcription is asymmetric at {_a}{_b}")


def blosum62(wt: str, mut: str) -> int:
    """Substitution score for ``wt -> mut``. Higher means more interchangeable."""
    try:
        return BLOSUM62[(wt, mut)]
    except KeyError as exc:
        raise ValueError(f"BLOSUM62 is defined over the 20 standard residues; got {wt!r}->{mut!r}") from exc
