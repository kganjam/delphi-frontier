/* Views: Frontier and Knowledge. Each view function returns {html, after(root)}; all text is escaped by html``. */
(function () {
  const DF = window.DF; const { html, raw, esc, fmt } = DF;

  const U = (DF.ui = {
    pill: (text, cls = "") => html`<span class="pill ${cls}">${text}</span>`,
    src: (id, label, cls = "srclink") => html`<a class="${cls}" href="${DF.hrefWith({ src: id })}" data-src="${id}">${label}</a>`,
    ext: (url, label) => (DF.safeUrl(url) ? html`<a href="${url}" target="_blank" rel="noopener noreferrer">${label}<span class="sr"> (opens in a new tab)</span></a>` : html`<span class="faint">${label} (no link)</span>`),
    empty: (msg) => html`<p class="empty">${msg}</p>`,
    sha: (s) => html`<code class="sha" title="${s}">${String(s || "").slice(0, 12)}…</code>`,
  });

  const CATEGORY = {
    checked: { cls: "cat-checked", text: "Upstream label: checked", help: "An upstream project review recorded a check for this record. It is not accepted by this site and is not a truth score." },
    related: { cls: "cat-related", text: "Upstream label: related formal result", help: "A neighbouring formal result exists; the target statement is unestablished." },
    unchecked: { cls: "cat-unchecked", text: "Upstream label: no check recorded", help: "No corresponding check in the upstream inventory. That does not mean the claim is unknown to science." },
    question: { cls: "cat-question", text: "Upstream label: open question", help: "The upstream review treats this as a question needing evidence." },
  };
  DF.CATEGORY = CATEGORY;
  const KIND_LABEL = {
    project_formalization_gap: "Project gap: formalisation", empirical_bridge_gap: "Empirical bridge gap", project_computational_question: "Project computational question",
    project_source_review_gap: "Project gap: source review", project_coordination_question: "Project coordination question", project_methods_question: "Project methods question",
    resolved_project_scope_correction: "Resolved scope correction", generated_engineering_question: "Generated engineering question",
  };
  const KIND_NOTE = {
    generated_engineering_question: "Generated by this build from unknowns recorded in the flying-fish report. Not a field-wide open problem.",
  };
  const kindText = (k) => KIND_LABEL[k] || k;

  function questions(snap) {
    const seed = snap.problems.map((p) => ({ ...p, origin: "curated" }));
    const gen = (snap.mission.engineering_questions || []).map((q) => ({ ...q, derived_from: q.origin, origin: "generated", claim_ids: [], unlocks: [], acceptance: q.settles_by }));
    return [...seed, ...gen];
  }
  DF.questions = questions; DF.kindText = kindText; DF.KIND_NOTE = KIND_NOTE;

  function depLevels(qs) {
    const byId = Object.fromEntries(qs.map((q) => [q.id, q])); const lvl = {}; const seen = new Set();
    const visit = (id) => { if (lvl[id] !== undefined) return lvl[id]; if (seen.has(id)) return 0; seen.add(id); const q = byId[id]; lvl[id] = Math.max(-1, ...(q.depends_on || []).filter((d) => byId[d]).map(visit)) + 1; return lvl[id]; };
    qs.forEach((q) => visit(q.id)); return lvl;
  }

  /* ----------------------------- KNOWLEDGE ----------------------------- */
  DF.views.knowledge = function (snap, route) {
    const tab = route.params.tab || "claims"; const sel = route.parts[1] || null;
    const tabs = [["claims", "Claims & equations"], ["graph", "Claim graph"], ["mission", "Flying-fish equations"], ["catalog", "Catalog"]];
    const nav = html`<nav class="subnav" aria-label="Knowledge sections">${tabs.map(([k, t]) => html`<a href="${DF.href("/knowledge" + (sel && (k === "claims" || k === "graph") ? "/" + sel : ""), { tab: k })}" aria-current="${tab === k ? "page" : "false"}">${t}</a>`)}</nav>`;
    const head = html`<section class="pagehead"><h1>Knowledge</h1><p class="lede">Claims, equations, proofs, data and the context that bounds them. Equation, evidence kind and assumptions are always shown with the claim. <b>A claim's upstream label is an assertion made elsewhere, not acceptance here.</b></p>${nav}</section>`;
    if (tab === "graph") return knowledgeGraph(snap, route, head, sel);
    if (tab === "mission") return missionEquations(snap, head);
    if (tab === "catalog") return DF.catalogView(snap, route, head, "/knowledge");
    return knowledgeClaims(snap, route, head, sel);
  };

  function knowledgeClaims(snap, route, head, sel) {
    const f = { q: route.params.q || "", group: route.params.group || "", cat: route.params.cat || "" };
    const groups = [...new Set(snap.claims.map((c) => c.group))];
    const list = snap.claims.filter((c) => (!f.group || c.group === f.group) && (!f.cat || c.category === f.cat) && (!f.q || JSON.stringify(c).toLowerCase().includes(f.q.toLowerCase())));
    const c = snap.claims.find((x) => x.id === sel);
    const row = (x) => html`<li class="qrow ${x.id === sel ? "on" : ""}"><a href="${DF.href("/knowledge/" + x.id, f)}" aria-current="${x.id === sel ? "true" : "false"}"><span class="qid">${x.short}</span><span class="qt">${x.label}</span>
      <span class="qmeta">${U.pill(CATEGORY[x.category].text, CATEGORY[x.category].cls)} ${U.pill(x.group, "grp")}</span></a></li>`;
    return {
      html: html`${head}<section><h2 class="sr">Claims and equations</h2>
        <p class="note">${snap.scope.claims}. These are extracted records of classic results; the page shows what the upstream review said about each, plus the statement's own stated assumptions.</p>
        <form class="filters" role="search" data-form="knowledge" aria-label="Filter claims">
          <input type="hidden" name="tab" value="claims">
          <label>Search <input type="search" name="q" value="${f.q}" placeholder="claim, symbol or source"></label>
          <label>Group <select name="group"><option value="">all</option>${groups.map((g) => html`<option ${g === f.group ? raw("selected") : ""}>${g}</option>`)}</select></label>
          <label>Upstream label <select name="cat"><option value="">all</option>${Object.keys(CATEGORY).map((k) => html`<option value="${k}" ${k === f.cat ? raw("selected") : ""}>${CATEGORY[k].text}</option>`)}</select></label>
          <button class="btn" type="submit">Apply</button>${f.q || f.group || f.cat ? html`<a class="btn ghost" href="${DF.href("/knowledge" + (sel ? "/" + sel : ""))}">Clear</a>` : ""}
        </form>
        <p class="count" role="status">${list.length} of ${snap.claims.length} claims shown</p>
        <div class="split"><div class="list-col">${list.length ? html`<ul class="qlist">${list.map(row)}</ul>` : U.empty("No claim matches these filters.")}</div>
        <div class="detail-col" id="cdetail" tabindex="-1">${c ? claimDetail(c, snap) : html`<div class="detail-empty"><h3>Select a claim</h3><p>Pick a claim to read its statement, equations, context and evidence kinds, and to open its source records.</p></div>`}</div></div>
      </section>`,
      after(root) { DF.renderMath(root); DF.bindForm(root, "knowledge", (v) => DF.href("/knowledge" + (sel ? "/" + sel : ""), v)); },
    };
  }

  function claimDetail(c, snap) {
    const bridges = snap.bridges.filter((b) => b.from === c.id || b.to === c.id);
    const byId = Object.fromEntries(snap.claims.map((x) => [x.id, x]));
    return html`<article class="detail claim" aria-labelledby="cd-t">
      <p class="eyebrow">${c.group}</p><h3 id="cd-t">${c.label}</h3>
      <p>${U.pill(CATEGORY[c.category].text, CATEGORY[c.category].cls)} <span class="small faint">${CATEGORY[c.category].help}</span></p>
      <h4>Statement</h4><p>${c.statement}</p>
      <h4>Equation</h4>${DF.mixedSpan(c.math)}
      <h4>Context and assumptions</h4><p>${c.context}</p>
      <h4>Upstream finding</h4><p><b>${c.review_title}.</b> ${c.finding}</p>
      <h4>Evidence kinds</h4>
      ${c.evidence.length ? html`<ul class="evlist">${c.evidence.map((e) => html`<li>${U.pill(e.kind, "ev")} ${U.ext(e.url, e.label)}</li>`)}</ul>` : html`<p class="faint">No evidence record linked.</p>`}
      <p class="small faint">Evidence labelled “related formal source” or “browser calculation” does not by itself establish the statement for this record's target.</p>
      <h4>Next action (upstream)</h4><p>${c.next_action}</p>
      ${bridges.length ? html`<h4>Linked claims</h4><ul>${bridges.map((b) => { const other = byId[b.from === c.id ? b.to : b.from]; return html`<li>${U.pill(b.kind === "proposed" ? "proposed bridge (not derived)" : "scope boundary", "br-" + b.kind)} <a href="${DF.href("/knowledge/" + other.id)}">${other.short}</a>: ${b.label}</li>`; })}</ul>` : ""}
      <h4>Source</h4><p>${c.source}</p>
      <p class="small">${U.src("claim:" + c.id, "Open source record")} · record sha256 ${U.sha(c.record_sha256)} · ${U.ext(c.source_url, "Upstream record on GitHub")} <span class="faint">(repository may require access)</span></p>
    </article>`;
  }

  function knowledgeGraph(snap, route, head, sel) {
    const groups = [...new Set(snap.claims.map((c) => c.group))]; const row = {};
    const nodes = snap.claims.map((c) => { const col = groups.indexOf(c.group); row[col] = (row[col] ?? -1) + 1; return { id: c.id, label: c.short, sub: CATEGORY[c.category].text.replace("Upstream label: ", ""), col, row: row[col], cls: CATEGORY[c.category].cls }; });
    const edges = snap.bridges.map((b, i) => ({ id: "b" + i, from: b.from, to: b.to, kind: b.kind === "proposed" ? "proposed" : "scope", label: b.label }));
    const sc = sel && sel.startsWith("b") ? edges.find((e) => e.id === sel) : null; const claim = snap.claims.find((c) => c.id === sel);
    const edgeDetail = sc ? html`<article class="detail"><p class="eyebrow">Edge · ${sc.kind}</p><h3>${snap.claims.find((c) => c.id === sc.from).short} → ${snap.claims.find((c) => c.id === sc.to).short}</h3>
      <p>${sc.label}</p><p class="note small">${sc.kind === "proposed" ? "A proposed bridge is a tentative analogy or transfer. It is not a derivation, and no derivation edge is recorded in this seed." : "A scope edge marks where one claim's result stops short of the other. It is a boundary, not a proof step."}</p>
      <p><a href="${DF.href("/knowledge/" + sc.from, { tab: "claims" })}">Open ${snap.claims.find((c) => c.id === sc.from).short}</a> · <a href="${DF.href("/knowledge/" + sc.to, { tab: "claims" })}">Open ${snap.claims.find((c) => c.id === sc.to).short}</a></p></article>` : null;
    const detail = edgeDetail || (claim ? claimDetail(claim, snap) : html`<div class="detail-empty"><h3>Select a node or an edge</h3><p>Nodes are claims, grouped by upstream topic. Edges are the ${edges.length} recorded links between them, each labelled by type. The list below is the same graph as text.</p></div>`);
    return {
      html: html`${head}<section><h2 class="sr">Claim graph</h2>
        <p class="note">Positions are by topic group only; they carry no other meaning. There are <b>no derivation edges</b> in this seed: every recorded link is a proposed bridge (tentative analogy or transfer) or a scope boundary. Node colour is the upstream review label, not scientific truth.</p>
        <div class="split graphsplit"><div class="graphhost" id="kg"></div><div class="detail-col" id="kdetail" tabindex="-1">${detail}</div></div>
        <h3>The same links as a list</h3>
        <div class="tablewrap"><table><thead><tr><th>From</th><th>Type</th><th>To</th><th>Label</th></tr></thead><tbody>
          ${edges.map((e) => html`<tr><td>${snap.claims.find((c) => c.id === e.from).short}</td><td>${U.pill(e.kind === "proposed" ? "proposed (tentative)" : "scope boundary", "br-" + (e.kind === "proposed" ? "proposed" : "scope"))}</td><td>${snap.claims.find((c) => c.id === e.to).short}</td><td>${e.label} <a href="${DF.href("/knowledge/" + e.id, { tab: "graph" })}">Inspect</a></td></tr>`)}
        </tbody></table></div></section>`,
      after(root) {
        DF.graph.draw(root.querySelector("#kg"), {
          columns: groups.map((g) => ({ title: g })), nodes, edges, selected: sc ? { type: "edge", id: sel } : { type: "node", id: sel }, ariaLabel: "Claim graph",
          legend: Object.keys(CATEGORY).map((k) => ({ cls: CATEGORY[k].cls, text: CATEGORY[k].text })),
          onSelect(type, id) { DF.go(DF.href("/knowledge/" + id, { tab: "graph" })); },
        });
        DF.renderMath(root);
      },
    };
  }

  function missionEquations(snap, head) {
    const m = snap.mission;
    const eq = (e) => html`<article class="eqcard"><h3>${e.name}</h3><div class="eq-math">${DF.texSpan(e.latex, true)}</div>
      <p>${U.pill(e.kind, "ev")} ${U.src("src:" + e.source, DF.sourceTitle(snap, e.source))}</p>
      <dl><dt>Variables</dt><dd>${e.variables}</dd><dt>Context and limits</dt><dd>${e.context}</dd></dl></article>`;
    return {
      html: html`${head}<section><h2 class="sr">Flying-fish equations</h2><p class="note">Equations for the flying-fish mission. Each carries its variables, its context and the source that supports it. Numbers computed from them on the Engineering page are <b>browser arithmetic on published fits</b>, not simulation.</p>
        <div class="eqgrid">${m.equations.map(eq)}</div>
        <h3>Measured wing-loading fits (Fish 1990, Table II)</h3>
        <div class="tablewrap"><table><thead><tr><th>Genus</th><th>n</th><th>Measured WL range (N/m²)</th><th>a</th><th>b</th><th>95% CI on b</th><th>versus isometry (b = 0.33)</th></tr></thead><tbody>
          ${m.genus_fits.map((g) => html`<tr><td><i>${g.genus}</i></td><td>${g.n}</td><td>${g.range[0]}–${g.range[1]}</td><td>${g.a}</td><td>${g.b}</td><td>${g.ci[0]}–${g.ci[1]}</td><td>${g.vs_isometry}</td></tr>`)}</tbody></table></div>
        <p class="small faint">${m.fit_note}</p></section>`,
      after(root) { DF.renderMath(root); },
    };
  }
  DF.sourceTitle = (snap, id) => { const s = snap.mission.sources.find((x) => x.id === id); return s ? s.short || s.cite : id; };
})();
