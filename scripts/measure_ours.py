"""Measure what Delphi Frontier actually has ON MAIN, versus what sits on task branches.

A pitch that lists search, beliefs, compute and deployment is describing seven unmerged
branches. This script reads git rather than taking anyone's word for it, so the "ours" column
of the prior-art matrix cannot drift from the repository.
"""
from __future__ import annotations
import json, subprocess, sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRANCHES = ["work/beliefs-adapter", "work/collab-mcp", "work/frontier-compute",
            "work/frontier-search", "work/guilds-engineering", "work/site",
            "codex/frontier-demo-20261031"]


def git(*a):
    return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def test_defs(ref):
    n = 0
    for f in git("ls-tree", "-r", "--name-only", ref).splitlines():
        if f.startswith("tests/") and f.endswith(".py"):
            n += git("show", f"{ref}:{f}").count("\ndef test_")
    return n


def main():
    main_sha = git("rev-parse", "origin/main")
    out = {
        "measured_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "note": "Generated by scripts/measure_ours.py from git. Nothing here is hand-entered.",
        "main": {
            "sha": main_sha,
            "committed_at": git("log", "-1", "--format=%cI", main_sha),
            "commits": int(git("rev-list", "--count", main_sha) or 0),
            "test_functions": test_defs("origin/main"),
            "files": len(git("ls-tree", "-r", "--name-only", "origin/main").splitlines()),
        },
        "task_branches_NOT_on_main": [],
        "caveat": ("A capability present only on a task branch is NOT a capability of this "
                   "project's main line. Any claim that rests on one must name the branch."),
    }
    for b in BRANCHES:
        ref = f"origin/{b}"
        if not git("rev-parse", "--verify", "--quiet", ref):
            continue
        added = [l.split("\t", 1)[1] for l in git("diff", "--name-status",
                 f"origin/main...{ref}").splitlines() if l.startswith("A\t")]
        out["task_branches_NOT_on_main"].append({
            "branch": b,
            "sha": git("rev-parse", ref)[:12],
            "commits_ahead_of_main": int(git("rev-list", "--count", f"origin/main..{ref}") or 0),
            "files_added": len(added),
            "test_functions_total_on_branch": test_defs(ref),
            "representative_additions": sorted(added)[:8],
        })
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
