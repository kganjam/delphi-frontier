#!/usr/bin/env python3
"""Render the crawlable markdown twin of every Studio design space from the same files its page reads.

A page and its document must not drift, so neither is written by hand: both read
site/content/design-spaces/<id>.json (the authored prose), results/<id>/index.json (which studies exist and what
their figures are called) and the per-study result files. A study declared in the index and missing from the tree
is written out as declared-and-absent here exactly as the page renders it. Each design space names its own output
file in its content JSON ("doc"), so adding one needs no edit here.

    python3 scripts/designspace_doc.py                   # write every design space's document
    python3 scripts/designspace_doc.py --check           # exit 1 if any committed file is not what this would write
    python3 scripts/designspace_doc.py --id limbless-mouse   # just one
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT_DIR = ROOT / "site/content/design-spaces"


def design_space_ids() -> list[str]:
    """The directory listing is the registry, exactly as it is for the site build."""
    return sorted(f.stem for f in CONTENT_DIR.glob("*.json")) if CONTENT_DIR.is_dir() else []


def head(k: str) -> str:
    """A key is its own heading: the route file decides what sections it has, and one it adds later appears here without a
    code change. Nothing is reordered or renamed."""
    return re.sub(r"\biacuc\b", "IACUC", k.replace("_", " "), flags=re.I).capitalize().replace("Iacuc", "IACUC")


def emit(w, obj, skip=()) -> None:
    for k, v in (obj or {}).items():
        if k in skip or v is None or (isinstance(v, (list, dict)) and not v):
            continue
        w(f"**{head(k)}.**\n")
        if isinstance(v, str):
            w(v + "\n")
        elif isinstance(v, list):
            for x in v:
                if isinstance(x, str):
                    w(f"- {x}")
                    continue
                # A list of records usually leads with the field the list is named after; repeating that label is noise.
                ent = list(x.items())
                lead = bool(ent) and ent[0][0].lower() in k.lower() and isinstance(ent[0][1], str)
                body = (ent[0][1] + " " if lead else "") + " ".join(f"**{head(kk)}:** {vv}" for kk, vv in (ent[1:] if lead else ent))
                w(f"- {body.strip()}")
            w("")
        elif isinstance(v, dict):
            for kk, vv in v.items():
                w(f"- **{head(kk)}:** {vv}")
            w("")


def load(rel: str):
    p = ROOT / rel
    return json.loads(p.read_text()) if p.exists() else None


def esc(s) -> str:
    """Markdown table cells cannot carry a bare pipe or a newline."""
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def pmid_link(e: dict) -> str:
    p = e.get("pmid")
    return f"[PMID {p}](https://pubmed.ncbi.nlm.nih.gov/{p}/)" if p else ""


def render(ds_id: str) -> tuple[Path, str]:
    """Return (output path, text) for one design space. The output path is the design space's own `doc` key, so two design
    spaces cannot silently render over each other, and a design space that declares none is skipped by the caller."""
    content = CONTENT_DIR / f"{ds_id}.json"
    index = ROOT / f"results/{ds_id}/index.json"
    page = json.loads(content.read_text())
    ix = json.loads(index.read_text())
    out = ROOT / page["doc"]
    routes = load(ix["routes"]["data"]) or {}
    rows = routes.get("routes", [])
    # Evidence strength is each design space's own vocabulary; the route index may label it, and an unlabelled value still prints.
    ev_text = dict((ix.get("routes") or {}).get("evidence_labels") or {})
    L: list[str] = []
    w = L.append

    w(f"# {page.get('doc_title') or page['title'] + ': the design space'}\n")
    w("Generated by `scripts/designspace_doc.py` from the same files the live page reads, so the two cannot drift.")
    if page.get("live_url"):
        w(f"The interactive version, with the figures and the filterable route list, is at <{page['live_url']}>.")
    w("")
    w(f"**The question.** {page['goal']}\n")

    ans = page.get("answer", {})
    w(f"## {ans.get('headline', 'The answer')}\n")
    for para in ans.get("paragraphs", []):
        w(para + "\n")
    if ans.get("precision_note"):
        w(f"> {ans['precision_note']}\n")

    rec = routes.get("recommendation")
    if rec:
        w("## " + ((ix.get("routes") or {}).get("recommendation_title") or "If you asked us to actually do it") + "\n")
        named = next((r for r in rows if r.get("id") == rec.get("single_best_route")), None)
        if named:
            w(f"**The route.** {named.get('title')} (`{named['id']}`)\n")
        emit(w, rec, skip=("single_best_route",))

    w(f"## The design space: {len(rows)} routes\n")
    w("Every row is a published perturbation or a bounded proposal, with its own evidence level. "
      "**None of them has been attempted here.** Sources carry read levels: a listing is not a reading.\n")
    declared = [s["key"] for s in page.get("scales", [])]
    for sc in page.get("scales", []):
        group = [r for r in rows if r.get("scale") == sc["key"]]
        if not group:
            continue
        w(f"### {sc['label']} — {len(group)} route{'s' if len(group) != 1 else ''}\n")
        w(f"{sc.get('blurb', '')}\n")
        w("| Route | Intervention | Predicted phenotype | Evidence | Reversible | Lethality risk | Difficulty |")
        w("|---|---|---|---|---|---|---|")
        for r in group:
            ev = ev_text.get(r.get("evidence_strength"), str(r.get("evidence_strength") or "not stated").replace("_", " "))
            w(f"| **{esc(r.get('title') or r.get('id'))}** | {esc(r.get('intervention'))} | {esc(r.get('predicted_phenotype'))} "
              f"| {esc(ev)} | {esc(r.get('reversibility'))} | {esc(r.get('lethality_risk'))} | {esc(r.get('difficulty'))} |")
        w("")
        for r in group:
            cites = [f"{e.get('cite', '')} {pmid_link(e)} ({e.get('read_level', 'read level not stated')})".strip()
                     for e in r.get("evidence", [])]
            w(f"**{r.get('title') or r.get('id')}.** {r.get('mechanism', '')}")
            w(("Sources: " + "; ".join(cites) if cites else "No source is attached to this route, so it is a proposal only.") + "\n")
    unplaced = [r for r in rows if r.get("scale") not in declared]
    if unplaced:
        w(f"### Unplaced — {len(unplaced)}\n")
        w("These routes name a scale the page does not declare "
          f"({', '.join(sorted({str(r.get('scale')) for r in unplaced}))}). They are listed rather than dropped.\n")
        for r in unplaced:
            w(f"- **{r.get('title') or r.get('id')}** ({r.get('scale')}): {r.get('predicted_phenotype', '')}")
        w("")

    w("## What we ran\n")
    w((page.get("studies_note") or f"{len(ix['studies'])} studies, each a computed model or analysis. None is an observation.") + "\n")
    for s in ix["studies"]:
        data = load(s["data"])
        w(f"### {s['title']}\n")
        w(f"*{s.get('kind', 'computed')} · {s.get('scale', '')} scale*\n")
        if s.get("question"):
            w(f"**The design question it answers.** {s['question']}\n")
        w(s.get("summary", "") + "\n")
        if data is None:
            w(f"**Declared and not present.** The result file `{s['data']}` is not in this tree. "
              "It is listed rather than hidden.\n")
            continue
        if data.get("headline"):
            w(f"**{data['headline']}**\n")
        for f in s.get("figures", []):
            present = (ROOT / f"results/limbless-mouse/figures/{f['file']}").exists()
            w(f"- Figure `{f['file']}`{'' if present else ' — declared and not present'}: {f.get('caption', '')}")
        if s.get("figures"):
            w("")
        params = (data.get("model") or {}).get("parameters") or data.get("parameters") or []
        if params:
            assumed = [p for p in params if p.get("status") == "assumed"]
            w(f"{len(params)} parameters, of which {len(assumed)} are assumed rather than sourced.\n")
        for lim in data.get("limitations", []):
            w(f"- {lim}")
        if data.get("limitations"):
            w("")
        w(f"Full result file: `{s['data']}`. Code: `{s.get('code', 'not stated')}`.\n")

    chain = page.get("chain", {})
    w(f"## {chain.get('title', 'The chain across scales')}\n")
    if chain.get("intro"):
        w(chain["intro"] + "\n")
    for i, k in enumerate(chain.get("links", []), 1):
        w(f"{i}. **{k['from']} → {k['to']}** — *{k['status']}*. {k['note']}")
    w("")
    if chain.get("verdict"):
        w(f"> {chain['verdict']}\n")

    genes = routes.get("judge_gene_candidates") or []
    if genes:
        rx = ix.get("routes") or {}
        w("## " + (rx.get("gene_table_title") or "Candidate genes, and what each would actually give you") + "\n")
        w((rx.get("gene_table_note") or "Several genes fit the description and they do not produce the same organism. The last "
           "column is the question that would tell them apart.") + "\n")
        w("| Gene | Evidence is in | What it would actually produce | The question that tells them apart |")
        w("|---|---|---|---|")
        for g in genes:
            pm = f" ([PMID {g['key_pmid']}](https://pubmed.ncbi.nlm.nih.gov/{g['key_pmid']}/))" if g.get("key_pmid") else ""
            w(f"| **{esc(g.get('gene') or g.get('name'))}**{pm} | {esc(g.get('species_of_evidence') or g.get('species'))} "
              f"| {esc(g.get('what_it_would_actually_produce') or g.get('effect'))} | {esc(g.get('distinguishing_question'))} |")
        w("")

    wel = routes.get("welfare")
    if wel:
        w("## " + ((ix.get("routes") or {}).get("welfare_title") or "Animal welfare and the 3Rs") + "\n")
        emit(w, wel)

    w("## What this page does not claim\n")
    for x in page.get("not_claimed", []):
        w(f"- {x}")
    for x in routes.get("limitations", []):
        w(f"- {x}")
    w("")
    closing = page.get("closing")
    if closing:
        w(f"## {closing['title']}\n")
        w(closing["text"] + "\n")
    w("---\n")
    w(f"Inputs: `{content.relative_to(ROOT)}`, `{index.relative_to(ROOT)}`, `{ix['routes']['data']}` and the per-study "
      f"result files named above. Regenerate with `python3 scripts/designspace_doc.py`; check with `--check`.")
    return out, "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if any committed file differs from what this would write")
    ap.add_argument("--id", help="render only this design space (default: every one declared)")
    args = ap.parse_args()
    ids = [args.id] if args.id else design_space_ids()
    if not ids:
        print("no design space is declared in site/content/design-spaces/", file=sys.stderr)
        return 1
    rc = 0
    for ds_id in ids:
        if not (CONTENT_DIR / f"{ds_id}.json").exists() or not (ROOT / f"results/{ds_id}/index.json").exists():
            print(f"{ds_id}: no content file or no results index; skipped", file=sys.stderr)
            continue
        if "doc" not in json.loads((CONTENT_DIR / f"{ds_id}.json").read_text()):
            print(f"{ds_id}: declares no \"doc\" output path; skipped")
            continue
        out, text = render(ds_id)
        if args.check:
            if (out.read_text() if out.exists() else "") != text:
                print(f"{out.relative_to(ROOT)} is stale; run python3 scripts/designspace_doc.py", file=sys.stderr)
                rc = 1
            else:
                print(f"{out.relative_to(ROOT)} is current")
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"wrote {out.relative_to(ROOT)} ({len(text)} bytes)")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
