#!/usr/bin/env python3
"""Render the crawlable markdown twin of Studio > Limbless mouse from the same files the page reads.

The page and this document must not drift, so neither is written by hand: both read
site/content/limbless-mouse.json (the authored prose), results/limbless-mouse/index.json (which studies exist
and what their figures are called) and the per-study result files. A study declared in the index and missing
from the tree is written out as declared-and-absent here exactly as the page renders it.

    python3 scripts/limbless_doc.py            # write docs/dossier/13-limbless-mouse-design-space.md
    python3 scripts/limbless_doc.py --check    # exit 1 if the file on disk is not what this would write
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "site/content/limbless-mouse.json"
INDEX = ROOT / "results/limbless-mouse/index.json"
OUT = ROOT / "docs/dossier/13-limbless-mouse-design-space.md"
LIVE = "https://studio.morphoswarm.ai/#/studio/limbless-mouse"

EV_TEXT = {"direct_mouse_phenotype": "direct mouse phenotype", "direct_other_species": "direct, another species",
           "cis_regulatory_inference": "cis-regulatory inference", "model_only": "model only", "proposed": "proposed"}


def load(rel: str):
    p = ROOT / rel
    return json.loads(p.read_text()) if p.exists() else None


def esc(s) -> str:
    """Markdown table cells cannot carry a bare pipe or a newline."""
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def pmid_link(e: dict) -> str:
    p = e.get("pmid")
    return f"[PMID {p}](https://pubmed.ncbi.nlm.nih.gov/{p}/)" if p else ""


def render() -> str:
    page = json.loads(CONTENT.read_text())
    ix = json.loads(INDEX.read_text())
    routes = load(ix["routes"]["data"]) or {}
    rows = routes.get("routes", [])
    L: list[str] = []
    w = L.append

    w(f"# 13. {page['title']}: the design space\n")
    w("Generated by `scripts/limbless_doc.py` from the same files the live page reads, so the two cannot drift.")
    w(f"The interactive version, with the figures and the filterable route list, is at <{LIVE}>.\n")
    w(f"**The question.** {page['goal']}\n")

    ans = page.get("answer", {})
    w(f"## {ans.get('headline', 'The answer')}\n")
    for para in ans.get("paragraphs", []):
        w(para + "\n")
    if ans.get("precision_note"):
        w(f"> {ans['precision_note']}\n")

    rec = routes.get("recommendation")
    if rec:
        w("## If you asked us to actually do it\n")
        if rec.get("headline"):
            w(f"**{rec['headline']}**\n")
        if rec.get("route"):
            w(f"**Route.** {rec['route']}\n")
        if rec.get("why"):
            w(rec["why"] + "\n")
        for i, s in enumerate(rec.get("steps", []), 1):
            w(f"{i}. {s}")
        if rec.get("steps"):
            w("")
        if rec.get("alternative"):
            w(f"**If the goal is a viable adult rather than an embryonic phenotype.** {rec['alternative']}\n")
        if rec.get("risks"):
            w("**What would sink it.** " + " ".join(rec["risks"]) + "\n")

    w(f"## The design space: {len(rows)} routes\n")
    w("Every row is a published perturbation or a bounded proposal, with its own evidence level. "
      "**None of them has been attempted here.** Sources carry read levels: a listing is not a reading.\n")
    declared = [s["key"] for s in page.get("scales", [])]
    for sc in page.get("scales", []):
        group = [r for r in rows if r.get("scale") == sc["key"]]
        if not group:
            continue
        w(f"### {sc['label']} — {len(group)} route{'s' if len(group) != 1 else ''}\n")
        w(f"{sc.get('blurb', '')}\n")
        w("| Route | Intervention | Predicted phenotype | Evidence | Reversible | Lethality risk | Difficulty |")
        w("|---|---|---|---|---|---|---|")
        for r in group:
            ev = EV_TEXT.get(r.get("evidence_strength"), str(r.get("evidence_strength") or "not stated").replace("_", " "))
            w(f"| **{esc(r.get('title') or r.get('id'))}** | {esc(r.get('intervention'))} | {esc(r.get('predicted_phenotype'))} "
              f"| {esc(ev)} | {esc(r.get('reversibility'))} | {esc(r.get('lethality_risk'))} | {esc(r.get('difficulty'))} |")
        w("")
        for r in group:
            cites = [f"{e.get('cite', '')} {pmid_link(e)} ({e.get('read_level', 'read level not stated')})".strip()
                     for e in r.get("evidence", [])]
            w(f"**{r.get('title') or r.get('id')}.** {r.get('mechanism', '')}")
            w(("Sources: " + "; ".join(cites) if cites else "No source is attached to this route, so it is a proposal only.") + "\n")
    unplaced = [r for r in rows if r.get("scale") not in declared]
    if unplaced:
        w(f"### Unplaced — {len(unplaced)}\n")
        w("These routes name a scale the page does not declare "
          f"({', '.join(sorted({str(r.get('scale')) for r in unplaced}))}). They are listed rather than dropped.\n")
        for r in unplaced:
            w(f"- **{r.get('title') or r.get('id')}** ({r.get('scale')}): {r.get('predicted_phenotype', '')}")
        w("")

    w("## What we ran\n")
    w("Three studies, each a **simulation or a sequence analysis**. None is an observation, none is calibrated to a "
      "measured mouse limb bud, and no part of any of them was run in an animal.\n")
    for s in ix["studies"]:
        data = load(s["data"])
        w(f"### {s['title']}\n")
        w(f"*{s.get('kind', 'computed')} · {s.get('scale', '')} scale*\n")
        if s.get("question"):
            w(f"**The design question it answers.** {s['question']}\n")
        w(s.get("summary", "") + "\n")
        if data is None:
            w(f"**Declared and not present.** The result file `{s['data']}` is not in this tree. "
              "It is listed rather than hidden.\n")
            continue
        if data.get("headline"):
            w(f"**{data['headline']}**\n")
        for f in s.get("figures", []):
            present = (ROOT / f"results/limbless-mouse/figures/{f['file']}").exists()
            w(f"- Figure `{f['file']}`{'' if present else ' — declared and not present'}: {f.get('caption', '')}")
        if s.get("figures"):
            w("")
        params = (data.get("model") or {}).get("parameters") or data.get("parameters") or []
        if params:
            assumed = [p for p in params if p.get("status") == "assumed"]
            w(f"{len(params)} parameters, of which {len(assumed)} are assumed rather than sourced.\n")
        for lim in data.get("limitations", []):
            w(f"- {lim}")
        if data.get("limitations"):
            w("")
        w(f"Full result file: `{s['data']}`. Code: `{s.get('code', 'not stated')}`.\n")

    chain = page.get("chain", {})
    w(f"## {chain.get('title', 'The chain across scales')}\n")
    if chain.get("intro"):
        w(chain["intro"] + "\n")
    for i, k in enumerate(chain.get("links", []), 1):
        w(f"{i}. **{k['from']} → {k['to']}** — *{k['status']}*. {k['note']}")
    w("")
    if chain.get("verdict"):
        w(f"> {chain['verdict']}\n")

    genes = routes.get("judge_gene_candidates") or []
    if genes:
        w("## \u201cHe said he identified a gene for it\u201d — what that could mean\n")
        w("Several genes fit that description and they do not produce the same animal. This is written so the question "
          "can be answered sensibly whichever one is meant, not to guess which it is.\n")
        w("| Gene | Species the evidence is in | What losing it does | Phenotype class | Evidence |")
        w("|---|---|---|---|---|")
        for g in genes:
            w(f"| **{esc(g.get('gene') or g.get('name'))}** | {esc(g.get('species'))} | {esc(g.get('effect') or g.get('what_it_does'))} "
              f"| {esc(g.get('phenotype'))} | {pmid_link(g)} {esc(g.get('read_level', ''))} |")
        w("")

    wel = routes.get("welfare")
    if wel:
        w(f"## {wel.get('title', 'Animal welfare and the 3Rs')}\n")
        for para in (wel.get("paragraphs") or ([wel["text"]] if wel.get("text") else [])):
            w(para + "\n")
        for key, head in (("refinements", "Refinements that change the answer"),
                          ("review_turns_on", "What a licence or IACUC review would turn on"),
                          ("non_animal_first", "What to do before any animal")):
            items = wel.get(key) or []
            if items:
                w(f"**{head}.**\n")
                for x in items:
                    w(f"- {x if isinstance(x, str) else '**' + str(x.get('name')) + '.** ' + str(x.get('note'))}")
                w("")

    w("## What this page does not claim\n")
    for x in page.get("not_claimed", []):
        w(f"- {x}")
    for x in routes.get("limitations", []):
        w(f"- {x}")
    w("")
    closing = page.get("closing")
    if closing:
        w(f"## {closing['title']}\n")
        w(closing["text"] + "\n")
    w("---\n")
    w(f"Inputs: `site/content/limbless-mouse.json`, `{INDEX.relative_to(ROOT)}`, `{ix['routes']['data']}` and the per-study "
      "result files named above. Regenerate with `python3 scripts/limbless_doc.py`; check with `--check`.")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs from what this would write")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run python3 scripts/limbless_doc.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
