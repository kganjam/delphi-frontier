"""Generate and run one Morpheus 2.3.9 Cellular Potts arm from the frozen protocol.

Usage:
  python -m engineering.xenomorph.cpm_model --arm dah --seed 1 --scale 1.0 --out DIR [--binary PATH] [--horizon-mcs N]

Writes DIR/model.xml, DIR/init_cells.json, runs Morpheus in DIR, writes DIR/run_receipt.json.
All values are dimensionless lattice units / Monte Carlo steps. No organism parameter is used.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
PROTOCOL = HERE / "protocol.json"


def sha(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def load_protocol() -> dict:
    return json.loads(PROTOCOL.read_text())


def place_cells_lattice(n: int, r: float, gap: float, jitter: float, center: float, seed: int, frac_a: float):
    """Dense dissociated suspension: the n sites of a simple-cubic lattice (spacing 2r+gap+2*jitter) nearest the
    centre, each displaced by an independent uniform +-jitter per axis.  Along any lattice axis two neighbours stay
    >= 2r+gap apart, so no two cells touch at t=0."""
    rng = np.random.default_rng(seed)
    a = 2 * r + gap + 2 * jitter
    k = int(math.ceil((n ** (1 / 3)) / 2)) + 2
    g = np.arange(-k, k + 1, dtype=float)
    P = np.stack(np.meshgrid(g, g, g, indexing="ij"), -1).reshape(-1, 3) + 0.5  # body-centred about origin
    tie = rng.uniform(0, 1e-6, len(P))  # seeded tie-break among equal radii
    P = P[np.lexsort((tie, np.linalg.norm(P, axis=1)))][:n] * a
    P = P + rng.uniform(-jitter, jitter, P.shape)
    types = np.array(["A"] * int(round(n * frac_a)) + ["B"] * (n - int(round(n * frac_a))))
    rng.shuffle(types)
    return P + center, types


def place_cells(n: int, r: float, gap: float, ball: float, center: float, seed: int, frac_a: float):
    """Random sequential addition inside a ball; centres >= 2r+gap apart (no contact at t=0).
    Used only by the recorded low-density pilot (aggregation stalled into ~20 non-merging clusters)."""
    rng = np.random.default_rng(seed)
    dmin = 2 * r + gap
    pts: list[np.ndarray] = []
    tries = 0
    while len(pts) < n:
        tries += 1
        if tries > 2_000_000:
            raise RuntimeError(f"placement failed: {len(pts)}/{n} cells")
        p = rng.uniform(-ball + r, ball - r, 3)
        if np.linalg.norm(p) > ball - r:
            continue
        if pts and np.min(np.linalg.norm(np.array(pts) - p, axis=1)) < dmin:
            continue
        pts.append(p)
    pts = np.array(pts) + center
    types = np.array(["A"] * int(round(n * frac_a)) + ["B"] * (n - int(round(n * frac_a))))
    rng.shuffle(types)
    return pts, types


def sphere_voxels(r: float) -> int:
    k = int(math.ceil(r)) + 1
    g = np.arange(-k, k + 1)
    X, Y, Z = np.meshgrid(g, g, g, indexing="ij")
    return int(np.count_nonzero(X**2 + Y**2 + Z**2 <= r * r))


def build_xml(proto: dict, arm: str, seed: int, scale: float, horizon: int | None,
              connectivity: bool = False) -> tuple[str, dict]:
    ip = proto["initial_population"]
    size = int(round(proto["lattice"]["base_size"] * scale))
    r = ip["cell_radius_base"] * scale
    gap = ip["gap_base"] * scale
    jit = ip["jitter_base"] * scale
    n = ip["n_cells"]
    pts, types = place_cells_lattice(n, r, gap, jit, size / 2.0, seed, ip["fraction_type_A"])
    ball = float(np.max(np.linalg.norm(pts - size / 2.0, axis=1)) + r)
    vt = sphere_voxels(r)
    J = proto["arms"][arm]["J"]
    T = proto["cells"]["temperature"]
    lam = proto["cells"]["volume_strength"]
    stop = horizon if horizon is not None else int(round(proto["time_horizon_mcs_base"] * scale**2))
    snap = int(round(proto["snapshot_interval_mcs_base"] * scale**2))

    # addendum 1: optional ConnectivityConstraint; default off leaves the frozen XML byte-identical
    cc = "\n            <ConnectivityConstraint/>" if connectivity else ""

    def pop(tname: str) -> str:
        arr = []
        for p, t in zip(pts, types):
            if t != tname:
                continue
            c = ", ".join(f"{v:.3f}" for v in p)
            arr.append(f'                <Arrangement displacements="1, 1, 1" repetitions="1, 1, 1">\n'
                       f'                    <Sphere radius="{r:.4f}" center="{c}"/>\n'
                       f'                </Arrangement>')
        return (f'        <Population size="0" type="{tname}">\n            <InitCellObjects mode="distance">\n'
                + "\n".join(arr) + '\n            </InitCellObjects>\n        </Population>')

    xml = f"""<MorpheusModel version="4">
    <Description>
        <Title>xenomorph-{arm}-s{seed}-x{scale}</Title>
        <Details>Generated by engineering/xenomorph/cpm_model.py from protocol sha256 {sha(PROTOCOL)}.
Template: Morpheus v2.3.9 Examples/CPM/CellSorting_3D.xml (Graner and Glazier 1992). Generic dimensionless DAH model.
Not a Xenobot, not any organism; no frog parameter is used.</Details>
    </Description>
    <Global/>
    <Space>
        <Lattice class="cubic">
            <Size value="{size}, {size}, {size}" symbol="size"/>
            <Neighborhood><Order>2</Order></Neighborhood>
        </Lattice>
        <SpaceSymbol symbol="l"/>
    </Space>
    <Time>
        <StartTime value="0"/>
        <StopTime value="{stop}"/>
        <RandomSeed value="{seed}"/>
        <TimeSymbol symbol="time"/>
    </Time>
    <CellTypes>
        <CellType class="medium" name="medium"/>
        <CellType class="biological" name="A">
            <VolumeConstraint strength="{lam}" target="{vt}"/>{cc}
        </CellType>
        <CellType class="biological" name="B">
            <VolumeConstraint strength="{lam}" target="{vt}"/>{cc}
        </CellType>
    </CellTypes>
    <CPM>
        <Interaction default="0.0">
            <Contact type1="A" type2="medium" value="{J['A-M']}"/>
            <Contact type1="B" type2="medium" value="{J['B-M']}"/>
            <Contact type1="A" type2="A" value="{J['A-A']}"/>
            <Contact type1="B" type2="B" value="{J['B-B']}"/>
            <Contact type1="A" type2="B" value="{J['A-B']}"/>
        </Interaction>
        <MonteCarloSampler stepper="edgelist">
            <MCSDuration value="1"/>
            <Neighborhood><Order>2</Order></Neighborhood>
            <MetropolisKinetics temperature="{T}"/>
        </MonteCarloSampler>
        <ShapeSurface scaling="norm">
            <Neighborhood><Distance>2.5</Distance></Neighborhood>
        </ShapeSurface>
    </CPM>
    <CellPopulations>
{pop('A')}
{pop('B')}
    </CellPopulations>
    <Analysis>
        <TiffPlotter compression="false" time-step="{snap}" OME-header="false" format="16bit" timelapse="false">
            <Channel exclude-medium="true" symbol-ref="cell.id"/>
            <Channel exclude-medium="true" symbol-ref="cell.type"/>
        </TiffPlotter>
    </Analysis>
</MorpheusModel>
"""
    meta = {"arm": arm, "seed": seed, "scale": scale, "lattice_size": size, "cell_radius": r, "gap": gap,
            "placement_ball_radius": ball, "n_cells": n, "volume_target": vt, "J": J, "temperature": T,
            "volume_strength": lam, "stop_mcs": stop, "snapshot_mcs": snap,
            "centers": pts.round(4).tolist(), "types": types.tolist()}
    return xml, meta


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", required=True)
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--out", required=True)
    ap.add_argument("--binary", default=os.environ.get("MORPHEUS_BIN", str(Path.home() / "opt/morpheus/morpheus-2.3.9")))
    ap.add_argument("--horizon-mcs", type=int, default=None)
    ap.add_argument("--no-run", action="store_true")
    ap.add_argument("--connectivity", action="store_true", help="addendum 1 supplementary arm")
    a = ap.parse_args(argv)
    proto = load_protocol()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    xml, meta = build_xml(proto, a.arm, a.seed, a.scale, a.horizon_mcs, a.connectivity)
    meta["connectivity_constraint"] = a.connectivity
    (out / "model.xml").write_text(xml)
    (out / "init_cells.json").write_text(json.dumps(meta) + "\n")
    if a.no_run:
        return 0
    cmd = [a.binary, "-file", "model.xml"]
    t0 = time.time()
    with open(out / "stdout.log", "w") as so:
        rc = subprocess.run(cmd, cwd=out, stdout=so, stderr=subprocess.STDOUT,
                            env={**os.environ, "OMP_NUM_THREADS": os.environ.get("OMP_NUM_THREADS", "1")}).returncode
    receipt = {"schema": "frontier.xenomorph.run/1", "command": " ".join(cmd), "cwd": str(out), "exit_code": rc,
               "wall_s": round(time.time() - t0, 2), "binary_sha256": sha(Path(a.binary)),
               "protocol_sha256": sha(PROTOCOL), "model_xml_sha256": sha(out / "model.xml"),
               "generator_sha256": sha(Path(__file__)), "arm": a.arm, "seed": a.seed, "scale": a.scale,
               "stop_mcs": meta["stop_mcs"], "n_tiffs": len(list(out.glob("*.tif")))}
    (out / "run_receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps(receipt))
    return rc


if __name__ == "__main__":
    sys.exit(main())
