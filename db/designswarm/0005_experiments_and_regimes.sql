-- ============================================================================================
-- Allocation policy as a treatment under test, and the regime-transition layer from
-- Wang & Buehler 2026 (arXiv:2606.01444). See docs/architecture/allocation-as-experiment.md
-- and docs/architecture/categorical-regime-transitions.md.
-- ============================================================================================

create table if not exists allocation_policy (
  id            text primary key,          -- random | round-robin | pressure-sc | voi | pressure-voi | thompson
  spec          jsonb not null,            -- the frozen specification, replayable against a recorded state
  rationale     text not null,
  is_control    boolean not null default false,
  created_at    timestamptz not null default now()
);

-- Pre-registration. Frozen BEFORE the first dispatch; analysis decided after seeing results is
-- recorded as exploratory and never promoted into the primary result.
create table if not exists experiment (
  id            text primary key,
  project_id    text references project(id),
  hypothesis    text not null,
  arms          text[] not null,
  primary_metric text not null,
  secondary_metrics text[],
  stopping_rule text not null,
  min_effect    text not null,             -- the smallest difference worth acting on
  frozen_at     timestamptz not null default now(),
  status        text not null default 'registered'
                check (status in ('registered','running','complete','abandoned')),
  outcome       text,
  replicated    boolean default false,
  exploratory_notes text
);

-- Written for EVERY arm that runs, including the ones that failed or embarrassed us.
create table if not exists policy_trial (
  id            bigserial primary key,
  experiment_id text references experiment(id),
  policy_id     text not null references allocation_policy(id),
  seed          int,
  started_at    timestamptz not null default now(),
  finished_at   timestamptz,
  n_dispatched  int default 0,
  n_claims      int default 0,
  n_survived    int default 0,             -- claims that survived adversarial challenge
  n_retracted   int default 0,             -- the metric that catches confident rubbish
  weighted_score double precision,         -- decisiveness-weighted survivors
  cost_usd      double precision,
  max_frontier_starvation_s int,
  notes         text
);

-- ------------------------------------------------------------------------------------------
-- Regime transitions. Wang & Buehler's distinction: SEARCH updates the state within a fixed
-- schema; DISCOVERY is a verified transition u : S-hat -> S-hat' that preserves accepted prior
-- artifacts, transports old evidence by left Kan extension, and EXPOSES RESIDUAL CONTENT not
-- generated by transport. Our evaluation kernel only ever did search; this is where a change of
-- representation is recorded as the distinct event it is.
-- ------------------------------------------------------------------------------------------
create table if not exists regime (
  id            text primary key,
  project_id    text references project(id),
  schema_note   text not null,             -- the admissible vocabulary: object and morphism types
  object_types  text[] not null,
  morphism_types text[],
  verifiers     text[],                    -- what counts as a check IN this regime
  opened_at     timestamptz not null default now(),
  closed_at     timestamptz
);

create table if not exists regime_transition (
  id            bigserial primary key,
  project_id    text references project(id),
  from_regime   text not null references regime(id),
  to_regime     text not null references regime(id),
  trigger       text not null,             -- the evidence that was INEXPRESSIBLE in the old regime
  transported   text,                      -- what carried over
  residual      text not null,             -- the new content NOT generated by transport: the discovery
  preserved_ok  boolean,                   -- were accepted prior artifacts preserved?
  mdl_before    double precision,          -- description-length gate, as in Builder/Breaker
  mdl_after     double precision,
  verified_by   text,
  accepted      boolean,
  reason        text not null,
  created_at    timestamptz not null default now()
);

-- Rejected edits and retractions are RETAINED, which Builder/Breaker does deliberately: the
-- record of what was tried and refused is part of the scientific state, not waste.
create table if not exists retraction (
  id            bigserial primary key,
  claim_id      bigint references claim(id),
  part_id       text references part(id),
  what          text not null,
  why           text not null,
  superseded_by bigint references claim(id),
  retracted_at  timestamptz not null default now()
);

create index if not exists idx_trial_exp on policy_trial(experiment_id);
create index if not exists idx_rt_proj   on regime_transition(project_id, accepted);
create index if not exists idx_retr_claim on retraction(claim_id);

insert into allocation_policy (id, spec, rationale, is_control) values
 ('random', '{"rule":"uniform over ready subproblems"}',
  'THE CONTROL. Without it no claim about any other policy means anything: many heuristics beat nothing and lose to uniform sampling, which is only ever discovered by running uniform sampling.', true),
 ('round-robin', '{"rule":"cycle frontiers evenly"}',
